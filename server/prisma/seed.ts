async function main() {
  console.log('🗑️  Bắt đầu dọn dẹp dữ liệu cũ...');
  await prisma.word.deleteMany({});
  console.log('✓ Đã xóa toàn bộ dữ liệu cũ.');

  // Loại bỏ từ trùng
  const seen = new Set<string>();
  const uniqueWords = words.filter((w) => {
    if (seen.has(w.word)) return false;
    seen.add(w.word);
    return true;
  });

  const ALL_DOMAINS = [
    'LIFE',
    'COMMUNICATION',
    'BUSINESS',
    'MEDICINE',
    'TECHNOLOGY',
    'SCIENCE',
    'TRAVEL',
    'FOOD',
    'SPORTS',
    'ART',
    'MUSIC',
    'EDUCATION',
    'ENVIRONMENT',
    'POLITICS',
    'FASHION',
    'FINANCE',
    'HISTORY',
    'LITERATURE',
    'LAW',
    'ENTERTAINMENT',
  ];

  const getDomainForWord = (word: string): string => {
    let sum = 0;
    for (let i = 0; i < word.length; i++) {
      sum += word.charCodeAt(i);
    }
    return ALL_DOMAINS[sum % ALL_DOMAINS.length];
  };

  const wordData = uniqueWords.map((w) => ({
    word: w.word,
    level: w.level,
    domain: getDomainForWord(w.word),
    ipa: w.ipa,
    definition: w.def,
    example: `Example: "${w.word}" - ${w.def}.`,
    exampleTranslation: `Ví dụ: "${w.word}" - ${w.def}.`,
  }));

  console.log(
    `\n📥 Đang chèn ${wordData.length} từ vựng Oxford thật vào cơ sở dữ liệu...`,
  );

  const chunkSize = 500;
  for (let i = 0; i < wordData.length; i += chunkSize) {
    const chunk = wordData.slice(i, i + chunkSize);
    await prisma.word.createMany({ data: chunk });
    console.log(
      `  → Đã chèn ${Math.min(i + chunkSize, wordData.length)}/${wordData.length}`,
    );
  }

  // Thống kê
  const total = await prisma.word.count();
  const byLevel = await prisma.word.groupBy({
    by: ['level'],
    _count: true,
    orderBy: { level: 'asc' },
  });
  const byDomain = await prisma.word.groupBy({ by: ['domain'], _count: true });

  console.log(`\n✅ Hoàn thành! Tổng số từ trong DB: ${total}`);
  console.log('\n📊 Phân bổ theo cấp độ:');
  byLevel.forEach((l) => console.log(`   ${l.level}: ${l._count} từ`));
  console.log('\n📊 Phân bổ theo lĩnh vực:');
  byDomain.forEach((d) => console.log(`   ${d.domain}: ${d._count} từ`));
}

main()
  .catch((e) => {
    console.error('Lỗi khi seed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
